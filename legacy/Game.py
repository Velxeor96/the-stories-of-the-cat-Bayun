def main():
    # Создаём клиент GigaChat
    giga = GigaChat(
        credentials=AUTH_KEY,
        scope="GIGACHAT_API_PERS",
        verify_ssl_certs=False,
        model="GigaChat-2-Pro"
    )

    # История сообщений в виде объектов ChatMessage
    messages = [
        ChatMessage(role="system", content=SYSTEM_PROMPT)
    ]

    print("=" * 50)
    print("Добро пожаловать в игру! (напишите 'выход' для завершения)")
    print("=" * 50)

    # Первый ход Мастера
    request = ChatCompletionRequest(messages=messages)
    response = giga.chat.create(request)
    answer = response.messages[0].content[0].text
    print("\nМастер:", answer)
    messages.append(ChatMessage(role="assistant", content=answer))

    # Основной цикл
    while True:
        user_input = input("\nВы: ")
        if user_input.lower() in ["выход", "exit", "quit"]:
            print("Игра завершена. До встречи!")
            break

        messages.append(ChatMessage(role="user", content=user_input))
        try:
            request = ChatCompletionRequest(messages=messages)
            response = giga.chat.create(request)
            answer = response.messages[0].content[0].text
            print("\nМастер:", answer)
            messages.append(ChatMessage(role="assistant", content=answer))
        except Exception as e:
            print("Ошибка при обращении к GigaChat:", e)
            print("Попробуйте ещё раз.")

if __name__ == "__main__":
    main()