def get_dream(char: dict) -> str:
    if not isinstance(char, dict):
        return "Тьма без снов."
    fid = str(char.get("faction_id") or "")
    ins = int(char.get("insanity", 0) or 0)
    pool = DREAMS.get(fid, ["Ты тонешь в тьме."])
    if ins >= 30:
        pool = pool + ["Хаос шепчет твоё имя. Ты почти готов ответить."]
    return random.choice(pool)
