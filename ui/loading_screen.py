def get_phrases(theme):
    base = list(PHRASES_BASE)
    extra = PHRASES_BY_THEME.get(str(theme or "dark"), [])
    combined = base + list(extra)
    random.shuffle(combined)
    return combined


# PATCH_16G — все загрузки используют шестерню Механикум.
# Тема фракции остаётся для фраз, но не для иконки.
def _sigil(theme):
    try:
        from ui.assets import sigil_svg
        return sigil_svg("mechanicum", 140)
    except Exception:
        return ""


def _sigil_inline(theme):
    try:
        from ui.assets import sigil_svg
        return sigil_svg("mechanicum", 96)
    except Exception:
        return ""


def full_html(theme, progress, phrase, subtitle="дух-машины пробуждается"):
    sig = _sigil(theme)
    if not sig:
        sig = ""
    return (
        "<div class='lx-wrap'>"
        + "<div class='lx-sigil'>" + sig + "</div>"
        + "<div class='lx-title'>INITIATIO</div>"
        + "<div class='lx-sub'>" + str(subtitle) + "</div>"
        + "<div class='lx-progress'>"
        + "<div class='lx-progress-fill' style='width:"
        + str(int(progress)) + "%;'></div>"
        + "</div>"
        + "<div class='lx-phrase'>" + str(phrase) + "</div>"
        + "<div class='lx-percent'>[ " + str(int(progress)) + "% ]</div>"
        + "</div>"
    )


def inline_html(theme, phrase=None, label="Когитатор Мастера обрабатывает запрос"):
    sig = _sigil_inline(theme)
    if phrase:
        phrase_block = (
            "<div class='lx-inline-phrase'>" + str(phrase) + "</div>"
        )
    else:
        phrase_block = ""
    return (
        _LOAD_CSS
        + "<div class='lx-inline'>"
        + "<div class='lx-sigil-inline'>" + sig + "</div>"
        + "<div class='lx-label'>" + str(label) + "</div>"
        + phrase_block
        + "</div>"
    )


def full_css():
    return _LOAD_CSS
