def roll_event(char: dict, chance_pct: int = 15) -> dict:
    if random.randint(1, 100) > chance_pct:
        return {"fired": False}
    fid = str(char.get("faction_id") or "")
    pool = EVENTS_BY_FACTION.get(fid, []) + GENERIC_EVENTS
    text = random.choice(pool)
    return {"fired": True, "text": text, "faction_id": fid}
